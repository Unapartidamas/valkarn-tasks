        const int MaxArity = 8;

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            // Only generate combinators when ValkarnTask is defined in source (not just referenced).
            // This prevents CS0538 errors from injecting partial struct into assemblies
            // that only reference ValkarnTask via ProjectReference.
            var hasValkarnTaskDefined = context.CompilationProvider.Select(
                static (c, _) =>
                {
                    var valkarnType = c.GetTypeByMetadataName("UnaPartidaMas.Valkarn.Tasks.ValkarnTask");
                    return valkarnType != null
                        && SymbolEqualityComparer.Default.Equals(valkarnType.ContainingAssembly, c.Assembly);
                });

            context.RegisterSourceOutput(hasValkarnTaskDefined, static (ctx, defined) =>
            {
                if (!defined) return;
                ctx.AddSource("ValkarnTask.WhenAll.Generated.g.cs", GenerateWhenAllSource());
                ctx.AddSource("ValkarnTask.WhenAny.Generated.g.cs", GenerateWhenAnySource());
            });
        }

