        // This generator produces arities 3-8 for typed WhenAll, 4-8 for void WhenAll,
        // 3-8 for void WhenAny, and 3-8 for typed WhenAny.

        const int MinTypedWhenAllArity = 3;
        const int MinVoidWhenAllArity = 4;
        const int MinVoidWhenAnyArity = 3;
